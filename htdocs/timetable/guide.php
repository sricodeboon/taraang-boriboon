      <h2 id="start"><span class="n">1</span>เริ่มต้นใช้งาน</h2>
      <ul>
        <li><b>ลองใช้ทันที</b> กดปุ่ม “ลองใช้ทันที ไม่ต้องสมัคร” ระบบสร้างโรงเรียนทดลองพร้อมข้อมูลตัวอย่างมัธยมให้ ข้อมูลทดลองจะถูกลบเองหลัง 2 วัน</li>
        <li><b>ใช้งานจริง</b> เข้าสู่ระบบด้วย Google หรือ LINE แล้วลงทะเบียนโรงเรียน พิมพ์จังหวัดก่อน ระบบจะแสดงรายชื่อโรงเรียนในจังหวัดนั้นให้เลือก อำเภอ ตำบล และรหัสโรงเรียนจะเติมให้อัตโนมัติ ถ้าไม่พบชื่อโรงเรียนพิมพ์เองได้</li>
        <li>เลือกเริ่มจาก <b>ตัวอย่างประถม</b> (ป.1–ป.6 ชั้นละห้อง) หรือ <b>ตัวอย่างมัธยม</b> (ม.1–ม.6 ชั้นละ 2 ห้อง) เพื่อดูว่าระบบทำงานอย่างไร หรือ <b>ตารางว่าง</b> เพื่อกรอกข้อมูลจริงตั้งแต่ต้น ตารางว่างเลือกให้ใส่ <b>รายวิชาพื้นฐานตามหลักสูตรแกนกลาง</b> ของประถม ม.ต้น หรือ ม.ปลาย มาให้ได้</li>
      </ul>
      <h3 style="font-size:1.05rem;margin-top:18px">เข้าและออกจากระบบ</h3>
      <ul>
        <li>เข้าด้วยบัญชีเดิมทุกครั้ง ระบบจะพาไปที่โรงเรียนของคุณพร้อมข้อมูลทั้งหมด เปิดจากคอมหรือมือถือเครื่องไหนก็เห็นข้อมูลชุดเดียวกัน</li>
        <li>ถ้าไม่ได้ใช้งานสักพัก ระบบจะ <b>ออกจากระบบให้เอง</b> ข้อมูลไม่หาย แค่กดเข้าสู่ระบบใหม่</li>
        <li><b>บัญชี Google กับบัญชี LINE นับเป็นคนละบัญชี</b> ถ้าลงทะเบียนด้วย LINE ให้เข้าด้วย LINE ทุกครั้ง ไม่เช่นนั้นระบบจะให้ลงทะเบียนโรงเรียนใหม่</li>
      </ul>

      <h2 id="periods"><span class="n">2</span>ตั้งโครงคาบ</h2>
      <p>ไปที่แท็บ <b>โครงคาบ · คาบล็อก</b></p>
      <ul>
        <li>เลือกจำนวน <b>วันเรียน</b> 5, 6 หรือ 7 วัน</li>
        <li>แต่ละแถวคือหนึ่งช่องเวลา ตั้งชื่อ เวลาเริ่ม เวลาจบ และชนิด <b>คาบเรียน</b> หรือ <b>พัก</b></li>
        <li>ปุ่ม <kbd>＋</kbd> แทรกคาบใหม่ด้านล่าง <kbd>↑</kbd> เลื่อนขึ้น <kbd>✕</kbd> ลบคาบ</li>
        <li>ตัวอย่าง: ประถมมักใช้วันละ 6 คาบ คาบละ 60 นาที มัธยมมักใช้วันละ 7–8 คาบ คาบละ 50 นาที</li>
      </ul>
      <div class="warn">ถ้าลบคาบหรือลดจำนวนวัน วิชาที่จัดไว้ในช่องนั้นจะถูกนำออกจากตาราง ระบบจะถามยืนยันก่อน ควรตั้งโครงคาบให้เสร็จก่อนเริ่มจัดตาราง</div>

      <h2 id="locks"><span class="n">3</span>คาบล็อก</h2>
      <p>คาบล็อกคือช่องที่ห้ามจัดวิชา เช่น กิจกรรมหน้าเสาธง ลูกเสือ เนตรนารี ชุมนุม แนะแนว ประชุมครู</p>
      <ul>
        <li>เลือก <b>ทุกห้องเรียน</b> หรือเฉพาะห้อง พิมพ์ชื่อกิจกรรม แล้ว <b>คลิกช่อง</b> ในตารางเล็กเพื่อล็อก คลิกซ้ำเพื่อปลดล็อก</li>
        <li>ช่องที่ล็อกจะแสดงเป็นลายขีด 🔒 ในตาราง การจัดอัตโนมัติจะข้ามช่องเหล่านี้ ในไฟล์ PDF และ Excel จะเป็นช่องสีม่วงอ่อนพร้อมชื่อกิจกรรม</li>
      </ul>

      <h2 id="data"><span class="n">4</span>ห้องเรียน ครู วิชา ห้องพิเศษ</h2>
      <p>ไปที่แท็บ <b>ข้อมูล</b> แล้วเลือกหมวดด้านบน</p>
      <ul>
        <li><b>ห้องเรียน</b> เช่น ป.1 หรือ ม.1/1 กดเพิ่มต่อจะได้ ม.1/2 อัตโนมัติ ช่อง “ระดับชั้น” ใช้ช่วยเลือกวิชาจากหลักสูตร คอลัมน์ “คาบที่มอบหมาย” เป็นสีแดงแปลว่ามอบหมายเกินจำนวนคาบว่างของห้อง</li>
        <li><b>ครู</b> ใส่ชื่อเต็มและชื่อย่อ (ชื่อย่อใช้ในช่องตาราง) ตั้ง “สูงสุด/วัน” (0 = ไม่จำกัด) และคลิกตารางเล็กเพื่อระบุ <b>คาบที่ไม่ว่าง</b> (สีแดง) เช่น ประชุม หรือสอนที่อื่น</li>
        <li><b>วิชา</b> รหัสวิชา ชื่อ และสีที่ใช้แสดงในตาราง
          <ul>
            <li>กดปุ่ม <b>“เพิ่มจากหลักสูตรแกนกลาง…”</b> เลือกชั้น (มัธยมเลือกภาคเรียนด้วย) ดูรายการแล้วกดเพิ่ม วิชาที่มีรหัสอยู่แล้วจะไม่ถูกเพิ่มซ้ำ เอาติ๊กออกได้ถ้าไม่ต้องการบางวิชา</li>
            <li>รหัสและจำนวนคาบเป็นค่าแนะนำ <b>ตรวจกับหลักสูตรสถานศึกษาของโรงเรียน</b> แล้วแก้ในตารางวิชาได้เลย</li>
          </ul></li>
        <li><b>ห้องพิเศษ</b> ห้องที่หลายห้องเรียนใช้ร่วมกัน เช่น ห้องคอม ห้องวิทย์ สนาม ระบบจะกันไม่ให้ใช้ซ้อนคาบ ไม่จำเป็นต้องมีก็ได้</li>
      </ul>

      <h2 id="assign"><span class="n">5</span>การสอน</h2>
      <p>“การสอน” คือการจับคู่ <b>วิชา × ห้องเรียน × ครู</b> พร้อมจำนวนคาบต่อสัปดาห์ นี่คือรายการที่ระบบนำไปจัดลงตาราง</p>
      <ul>
        <li><b>คาบ/สัปดาห์</b> จำนวนคาบของวิชานี้ในห้องนี้ คิดจากเวลาเรียนต่อปี ÷ 40 เช่น ภาษาไทย ป.1 200 ชั่วโมง/ปี = 5 คาบ/สัปดาห์</li>
        <li><b>คาบคู่</b> จำนวนครั้งที่ต้องเรียนสองคาบติดกัน เช่น วิทย์ปฏิบัติการ 4 คาบ ตั้งคาบคู่ 2 จะได้เรียนสองคาบติดกัน 2 ครั้ง</li>
        <li><b>ห้องพิเศษ</b> เลือกถ้าวิชานี้ต้องใช้ห้องเฉพาะ</li>
      </ul>
      <div class="tip">ก่อนจัด ลองรวมคาบ/สัปดาห์ของแต่ละห้อง ต้องไม่เกินจำนวนคาบว่าง (คาบเรียนทั้งหมด ลบคาบล็อก) และภาระสอนของครูแต่ละคนต้องไม่เกิน “สูงสุด/วัน × จำนวนวัน”</div>

      <h2 id="board"><span class="n">6</span>จัดตารางเองด้วยการลากวาง</h2>
      <ul>
        <li>แท็บ <b>จัดตาราง</b> เลือกมุมมอง <b>ห้องเรียน · ครู · ห้องพิเศษ</b> แล้วเลือกรายการ</li>
        <li>ลากวิชาจากแผงซ้ายมาวางในตาราง ขณะลาก ช่องที่วางได้จะเป็น <b style="color:var(--blue)">กรอบสีน้ำเงิน</b> ช่องที่ชนจะเป็น <b style="color:var(--danger)">กรอบสีแดง</b> พร้อมบอกเหตุผล</li>
        <li>ลากวิชาที่อยู่ในตารางเพื่อย้าย คลิกหนึ่งครั้งเพื่อเปิดเมนู ปักหมุด นำออก หรือดูตารางครูคนนั้น</li>
        <li>อยากวางทับทั้งที่ชน ให้กด <kbd>Shift</kbd> ค้างขณะปล่อย ช่องนั้นจะขึ้นป้าย “ชน” สีแดงให้กลับมาแก้ภายหลัง (บนมือถือและแท็บเล็ตวางทับไม่ได้ เพราะไม่มีปุ่ม Shift)</li>
        <li>ตัวเลขบนแผงซ้าย เช่น <kbd>1/3</kbd> คือเหลือต้องจัด 1 จากทั้งหมด 3 คาบ</li>
      </ul>

      <h2 id="auto"><span class="n">7</span>จัดอัตโนมัติ</h2>
      <ul>
        <li>กด <b>จัดอัตโนมัติ</b> ระบบจะวางทุกวิชาให้ไม่ชนกัน เคารพคาบล็อก คาบที่ครูไม่ว่าง จำนวนคาบสูงสุดต่อวัน คาบคู่ และห้องพิเศษ และพยายามกระจายวิชาเดียวกันไม่ให้ซ้ำวัน</li>
        <li>วิชาที่ <b>ปักหมุด 📌</b> จะไม่ถูกย้าย วิชาที่ลากวางเองจะถูกปักหมุดให้อัตโนมัติ จึงจัดคาบสำคัญเองก่อนแล้วให้ระบบจัดส่วนที่เหลือได้</li>
        <li>ปุ่ม <b>ล้างที่ไม่ปักหมุด</b> ลบเฉพาะคาบที่ระบบจัดให้ เพื่อลองจัดใหม่</li>
        <li>การคำนวณทำในเครื่องของผู้ใช้ ใช้เวลาไม่กี่วินาที</li>
        <li>ถ้ายังไม่เคยจัด จะมีกล่อง <b>ข้อมูลพร้อมแล้ว</b> เหนือตาราง บอกว่าขั้นต่อไปต้องกดอะไร และเตือนล่วงหน้าถ้าข้อมูลทำให้จัดไม่ครบ</li>
        <li>จัดแล้วเหลือคาบที่วางไม่ลง ระบบแสดง <b>สาเหตุและวิธีแก้</b> ค้างไว้เหนือตาราง พร้อมปุ่ม “ไปแก้ที่…” พาไปหน้าข้อมูลที่ต้องแก้ แก้แล้วกดจัดอัตโนมัติอีกครั้ง</li>
      </ul>
      <div class="warn"><b>ถ้าจัดไม่ครบ</b> ลองตรวจตามลำดับนี้
        <ol style="margin:6px 0 0">
