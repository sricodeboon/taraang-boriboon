// ---------- ประถม ป.1–ป.6 (รายปี · 40 สัปดาห์ · 1 คาบ/สัปดาห์ = 40 ชม./ปี) ----------
// เวลาเรียนพื้นฐานรวม 840 ชม./ปี = 21 คาบ/สัปดาห์ทุกชั้น (คำสั่ง สพฐ. 922/2561) — ตรวจแหล่งอ้างอิงใน data/SOURCES.md
// ป.1–3: ภาษาอังกฤษพื้นฐาน ≥ 120 ชม. + เพิ่มเติม 80 ชม. = 200 ชม./ปี (ประกาศ ศธ. 11 ก.ค. 2560) จึงลดสุขศึกษาฯ/ศิลปะเหลือ 40 ชม.
//        (รูปแบบที่โรงเรียนส่วนใหญ่ใช้); วิทยาศาสตร์และเทคโนโลยี 80 ชม. ตาม สสวท. (สาระเทคโนโลยีบูรณาการ/หรือเพิ่มเป็น 100)
//        วิทยาการคำนวณแยกเป็นรายวิชาเพิ่มเติม 40 ชม. ตามที่โรงเรียนนิยมจัด ("คอมพิวเตอร์")
// ป.4–6: วิทยาศาสตร์และเทคโนโลยี 120 = วิทยาศาสตร์ 80 + วิทยาการคำนวณ 40 และการงานอาชีพลดจาก 80 เหลือ 40 (คำสั่ง สพฐ. 921,922/2561 · สสวท.)
function primary(y) {
  const lower = y <= 3;
  const L = `ป.${y}`, c = (p, seq) => `${p}1${y}${seq}`;
  const s = (code, name, perWeek, color, type = 'พื้นฐาน') => ({ code, name, perWeek, color, type, hoursPerYear: perWeek * 40 });
  return [
    s(c('ท', '101'), `ภาษาไทย ${L}`, lower ? 5 : 4, COLOR.ท),
    s(c('ค', '101'), `คณิตศาสตร์ ${L}`, lower ? 5 : 4, COLOR.ค),
    s(c('ว', '101'), lower ? `วิทยาศาสตร์และเทคโนโลยี ${L}` : `วิทยาศาสตร์ ${L}`, 2, COLOR.ว),
    lower ? s(c('ว', '201'), `วิทยาการคำนวณ ${L}`, 1, COLOR.คำนวณ, 'เพิ่มเติม')
      : s(c('ว', '103'), `วิทยาการคำนวณ ${L}`, 1, COLOR.คำนวณ),
    s(c('ส', '101'), `สังคมศึกษา ศาสนาและวัฒนธรรม ${L}`, 2, COLOR.ส),
    s(c('ส', '102'), `ประวัติศาสตร์ ${L}`, 1, COLOR.ประวัติ),
    s(c('พ', '101'), `สุขศึกษาและพลศึกษา ${L}`, lower ? 1 : 2, COLOR.พ),
    s(c('ศ', '101'), `ศิลปะ ${L}`, lower ? 1 : 2, COLOR.ศ),
    s(c('ง', '101'), `การงานอาชีพ ${L}`, 1, COLOR.ง),
    s(c('อ', '101'), `ภาษาอังกฤษ ${L}`, lower ? 3 : 2, COLOR.อ),
    s(c('ส', '231'), `หน้าที่พลเมือง ${L}`, 1, COLOR.หน้าที่, 'เพิ่มเติม'),
    s(c('อ', '201'), `ภาษาอังกฤษเพื่อการสื่อสาร ${L}`, 2, COLOR.อ, 'เพิ่มเติม'),
  ];
}

// ---------- มัธยม (รายภาคเรียน · 20 สัปดาห์ · 1 คาบ/สัปดาห์ = 20 ชม. = 0.5 นก.) ม.ต้น ระดับ 2 · ม.ปลาย ระดับ 3 ----------
// ม.ต้น: พื้นฐาน 880 ชม./ปี = 22 นก./ปี = 11 นก./ภาค = 22 คาบ/สัปดาห์
//   วิทย์และเทคโนโลยี 160 ชม. (4 นก.) = วิทยาศาสตร์ 1.5 + เทคโนโลยี 0.5 นก./ภาค (ภาค 1 วิทยาการคำนวณ · ภาค 2 การออกแบบและเทคโนโลยี)
//   การงานอาชีพ 40 ชม. (1 นก.) · สังคมศึกษา 120 + ประวัติศาสตร์ 40 = 160 ชม. (4 นก.)
// ม.ปลาย: พื้นฐานรวม 3 ปี 1,640 ชม. = 41 นก. หลักสูตรกำหนดเป็นยอด 3 ปี การกระจายรายภาคด้านล่างเป็นแบบที่พบบ่อย:
//   ไทย/คณิต/อังกฤษ/สังคม 1 นก. ทุกภาค (6+6+6+6) · ประวัติศาสตร์ 0.5 นก. ม.4–5 (2) · วิทยาศาสตร์ 1 นก. + เทคโนโลยี 0.5 นก. ม.4–5 (4+2)
//   สุขศึกษาและพลศึกษา/ศิลปะ/การงานอาชีพ 0.5 นก. ทุกภาค (3+3+3) → 41 นก.
function secondary(level, y, sem) {
  const n = (y - 1) * 2 + sem;            // ลำดับวิชาต่อเนื่อง เช่น ม.2 ภาค 1 = ภาษาไทย 3
  const c = (p, sem1, sem2) => `${p}${level}${y}${sem === 1 ? sem1 : sem2}`;
  const s = (code, name, perWeek, color, type = 'พื้นฐาน') => ({ code, name, perWeek, color, type, credits: perWeek / 2 });
  const tech = sem === 1 ? `วิทยาการคำนวณ ${n}` : `การออกแบบและเทคโนโลยี ${n}`;
  if (level === 2) {
    return [
      s(c('ท', '101', '102'), `ภาษาไทย ${n}`, 3, COLOR.ท),
      s(c('ค', '101', '102'), `คณิตศาสตร์ ${n}`, 3, COLOR.ค),
      s(c('ว', '101', '102'), `วิทยาศาสตร์ ${n}`, 3, COLOR.ว),
      s(c('ว', '103', '104'), tech, 1, COLOR.คำนวณ),
      s(c('ส', '101', '103'), `สังคมศึกษา ศาสนาและวัฒนธรรม ${n}`, 3, COLOR.ส),
      s(c('ส', '102', '104'), `ประวัติศาสตร์ ${n}`, 1, COLOR.ประวัติ),
      s(c('พ', '101', '103'), `สุขศึกษา ${n}`, 1, COLOR.พ),
      s(c('พ', '102', '104'), `พลศึกษา ${n}`, 1, COLOR.พละ),
      s(c('ศ', '101', '102'), `ศิลปะ ${n}`, 2, COLOR.ศ),
      s(c('ง', '101', '102'), `การงานอาชีพ ${n}`, 1, COLOR.ง),
      s(c('อ', '101', '102'), `ภาษาอังกฤษ ${n}`, 3, COLOR.อ),
      s(c('ส', '231', '232'), `หน้าที่พลเมือง ${n}`, 1, COLOR.หน้าที่, 'เพิ่มเติม'),
    ];
  }
  const early = y <= 2;                    // ม.4–ม.5 มีวิทยาศาสตร์ เทคโนโลยี และประวัติศาสตร์
  return [
    s(c('ท', '101', '102'), `ภาษาไทย ${n}`, 2, COLOR.ท),
    s(c('ค', '101', '102'), `คณิตศาสตร์ ${n}`, 2, COLOR.ค),
    ...(early ? [
      s(c('ว', '101', '102'), `วิทยาศาสตร์ ${n}`, 2, COLOR.ว),
      s(c('ว', '103', '104'), tech, 1, COLOR.คำนวณ),
    ] : []),
    s(c('ส', '101', '103'), `สังคมศึกษา ศาสนาและวัฒนธรรม ${n}`, 2, COLOR.ส),
    ...(early ? [s(c('ส', '102', '104'), `ประวัติศาสตร์ ${n}`, 1, COLOR.ประวัติ)] : []),
    s(c('พ', '101', '102'), `สุขศึกษาและพลศึกษา ${n}`, 1, COLOR.พ),
    s(c('ศ', '101', '102'), `ศิลปะ ${n}`, 1, COLOR.ศ),
    s(c('ง', '101', '102'), `การงานอาชีพ ${n}`, 1, COLOR.ง),
    s(c('อ', '101', '102'), `ภาษาอังกฤษ ${n}`, 2, COLOR.อ),
    // แนวทางรายวิชาเพิ่มเติมหน้าที่พลเมือง สพฐ. 2557: ม.4–6 มี 2 รายวิชา ภาคละ 0.5 นก. → จัดไว้ที่ ม.4
    ...(y === 1 ? [s(c('ส', '231', '232'), `หน้าที่พลเมือง ${sem}`, 1, COLOR.หน้าที่, 'เพิ่มเติม')] : []),
  ];
}

const levels = [];
for (let y = 1; y <= 6; y++) levels.push({ id: `p${y}`, name: `ป.${y}`, band: 'primary', sem: 0, subjects: primary(y) });
for (const [band, level, first] of [['lower', 2, 1], ['upper', 3, 4]]) {
  for (let y = 1; y <= 3; y++) for (const sem of [1, 2]) {
    levels.push({ id: `m${first + y - 1}s${sem}`, name: `ม.${first + y - 1}`, band, sem, subjects: secondary(level, y, sem) });
  }
}
const curriculum = {
  v: 1,
  note: 'รายวิชาพื้นฐานตามโครงสร้างเวลาเรียนหลักสูตรแกนกลางการศึกษาขั้นพื้นฐาน พ.ศ. 2551 (ฉบับปรับปรุง พ.ศ. 2560) ปรับตามคำสั่ง สพฐ. 921–922/2561 ประกาศ ศธ. 11 ก.ค. 2560 และประกาศ ศธ. 19 ธ.ค. 2565 (ประวัติศาสตร์) พื้นฐานรวม ป.1–6 840 ชม./ปี (21 คาบ) ม.ต้น 880 ชม./ปี (22 นก., 22 คาบ) ม.ปลาย 1,640 ชม./3 ปี (41 นก.) โรงเรียนปรับเวลาแต่ละกลุ่มสาระได้เองถ้ายอดรวมคงเดิม ม.ปลายกำหนดเป็นยอด 3 ปี การกระจายรายภาคในที่นี้เป็นแบบที่พบบ่อย และรหัสวิชาเทคโนโลยี/หน้าที่พลเมืองต่างกันตามโรงเรียน รายการ "เพิ่มเติม" คือหน้าที่พลเมือง อังกฤษเพื่อการสื่อสาร และวิทยาการคำนวณ ป.1–3 ตรวจสอบกับโครงสร้างหลักสูตรสถานศึกษาของโรงเรียนก่อนใช้จริง',
  units: { perWeek: 'คาบ/สัปดาห์', hoursPerYear: 'ชม./ปี (ประถม, 40 สัปดาห์)', credits: 'หน่วยกิต/ภาคเรียน (มัธยม, 1 นก. = 40 ชม. = 2 คาบ/สัปดาห์ × 20 สัปดาห์)' },
  bands: { primary: 'ประถมศึกษา (ป.1–ป.6)', lower: 'มัธยมศึกษาตอนต้น (ม.1–ม.3)', upper: 'มัธยมศึกษาตอนปลาย (ม.4–ม.6)' },
  levels,
};
writeFileSync(join(ROOT, 'data/curriculum.json'), JSON.stringify(curriculum));

// ---------- ข้อมูลตัวอย่างโรงเรียนประถมขนาดเล็ก ป.1–ป.6 ชั้นละ 1 ห้อง ----------
const periods = [
  ['1', '08:30', '09:30'], ['2', '09:30', '10:30'], ['3', '10:30', '11:30'], ['พักกลางวัน', '11:30', '12:30', 'break'],
  ['4', '12:30', '13:30'], ['5', '13:30', '14:30'], ['6', '14:30', '15:30'],
].map(([label, start, end, type = 'class']) => ({ label, start, end, type }));
const LAST = periods.length - 1;
const classes = [1, 2, 3, 4, 5, 6].map((y) => ({ id: `c${y}`, name: `ป.${y}`, level: `ป.${y}` }));
const homeroom = ['นางสาวพิมพ์ชนก ใจงาม', 'นางอรุณี แสงทอง', 'นางสาววาสนา บุญมา', 'นายสมชาย รักเรียน', 'นางจันทร์เพ็ญ ศรีสุข', 'นายวีระพงษ์ ทองดี'];
const teachers = [
  ...homeroom.map((name, i) => ({ id: `t${i + 1}`, name, short: name.split(' ')[0].replace(/^(นางสาว|นาง|นาย)/, ''), maxPerDay: 5, unavailable: [] })),
  { id: 't7', name: 'นางสาวกัญญารัตน์ วงศ์วิทย์', short: 'กัญญารัตน์', maxPerDay: 5, unavailable: [] }, // วิทย์ + วิทยาการคำนวณ
  { id: 't8', name: 'นางสาวเจนจิรา อินทร์แก้ว', short: 'เจนจิรา', maxPerDay: 5, unavailable: [] },       // ภาษาอังกฤษ (พื้นฐาน)
  { id: 't9', name: 'นายธนวัฒน์ แข็งแรง', short: 'ธนวัฒน์', maxPerDay: 5, unavailable: [] },               // สุขศึกษาและพลศึกษา
];
const rooms = [{ id: 'r1', name: 'ห้องคอมพิวเตอร์', kind: 'ห้องคอมพิวเตอร์' }];
const subjects = [], assignments = [];
let sid = 0, aid = 0;
for (let y = 1; y <= 6; y++) {
  for (const s of primary(y)) {
    const id = `s${++sid}`;
    subjects.push({ id, code: s.code, name: s.name, color: s.color });
    const g = s.code[0], sub = s.code.slice(3);
    // อังกฤษพื้นฐาน = ครูอังกฤษ · อังกฤษเพื่อการสื่อสาร (เพิ่มเติม) = ครูประจำชั้น ให้ครูอังกฤษสอนไม่เกิน 25 คาบ/สัปดาห์
    const teacherId = g === 'ว' ? 't7' : g === 'อ' && s.type === 'พื้นฐาน' ? 't8' : g === 'พ' ? 't9' : `t${y}`;
    assignments.push({ id: `a${++aid}`, subjectId: id, classId: `c${y}`, teacherId, roomId: g === 'ว' && (sub === '103' || sub === '201') ? 'r1' : null, perWeek: s.perWeek, doubles: 0 });
  }
}
const locks = [
  { classId: null, day: 2, period: LAST, label: 'ลูกเสือ-เนตรนารี' },
  { classId: null, day: 3, period: LAST, label: 'แนะแนว' },
  { classId: null, day: 4, period: LAST, label: 'ชุมนุม' },
];
const sample = {
  meta: { format: 'sricodeboon-timetable', version: 1, school: 'โรงเรียนบ้านศรีโค้ด (ข้อมูลตัวอย่าง)', description: 'ข้อมูลสมมติของโรงเรียนประถมขนาดเล็ก ป.1–ป.6 ชั้นละ 1 ห้อง ครูประจำชั้นสอนวิชาหลัก มีครูวิทย์ ครูอังกฤษ และครูพละแยก ชื่อบุคคลทั้งหมดเป็นชื่อสมมติ', dayNames: ['จันทร์', 'อังคาร', 'พุธ', 'พฤหัสบดี', 'ศุกร์'] },
  term: { name: 'ภาคเรียนที่ 1 ปีการศึกษา 2569', days: 5, periods },
  classes, teachers, rooms, subjects, assignments, locks,
};
writeFileSync(join(ROOT, 'assets/solver/sample-primary.json'), JSON.stringify(sample, null, 1));
